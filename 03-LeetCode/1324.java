// 1342. 将数字变成 0 的操作次数
// easy
// 给你一个非负整数 num ，请你返回将它变成 0 所需要的步数。 如果当前数字是偶数，你需要把它除以 2 ；否则，减去 1 。
class Solution
{
    public int numberOfSteps(int num) {
        int x = 0;

        while (num > 0) {
            // 0x01 是十六进制表示的数字 1（其二进制形式为 0000 0001）
            // num & 0x01 是一个非常经典的按位与（Bitwise AND）操作，用来高效判断 num 是奇数还是偶数：
            // 当 num 是奇数时：它的二进制最低位是 1，与 0x01 做按位与的结果为 1
            // 当 num 是偶数时：它的二进制最低位是 0，与 0x01 做按位与的结果为 0
            x += (num > 1 ? 1 : 0) + (num & 0x01);
            // 因为在计算机内部，整数是以二进制形式存储的，右移一位，相当于除以二并向下取整，这里不写除以2是因为让计算机做位运算比除法要快得多。在底层硬件中，移位操作是非常基础的指令，因此在刷题或底层开发中，用右移来代替除以 2 是一种非常常见的高效写法。
            num >>= 1;
        }

        return x;
    }
}
